"""Общий визуальный язык для всех сообщений бота.

Раньше разделитель дублировался буквально в нескольких файлах (common.py,
services/leaderboard.py, захардкожен строкой в time_requests.py) — при смене
символа его пришлось бы менять в нескольких местах руками. Теперь один
источник правды.
"""

DIVIDER = "━━━━━━━━━━━━━━━━━━"


def header(emoji: str, title: str) -> str:
    """Единый заголовок экрана: эмодзи + ЗАГЛАВНЫЙ жирный титул + разделитель."""
    return f"{emoji} <b>{title.upper()}</b>\n{DIVIDER}"
